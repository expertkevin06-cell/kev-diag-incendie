  function buildIndex() {
    idxBrand = {}; idxModel = {}; idxEngine = {}; idxPower = {}; idxToken = {}; triIndex = {};
    brands.forEach(function (b) { push(idxBrand, key(b.name), b.name); (b.aliases || []).forEach(function (a) { push(idxBrand, key(a), b.name); }); });
    models.forEach(function (m, i) {
      push(idxModel, key(m.name), i); push(idxModel, key(m.brand + " " + m.name), i);
      (m.aliases || []).forEach(function (a) { push(idxModel, key(a), i); });
      push(idxBrand, key(m.brand), i);
      var toks = norm(m.brand + " " + m.name + " " + (m.aliases || []).join(" ")).split(" ").filter(Boolean);
      (m.variants || []).forEach(function (v) {
        push(idxEngine, key(v.engine), i);
        if (v.power) push(idxPower, v.power, i);
        toks = toks.concat(norm(v.engine).split(" ").filter(Boolean));
        if (v.power) toks.push(v.power);
      });
      uniq(toks).forEach(function (t) { push(idxToken, t, i); trigrams(t).forEach(function (g) { push(triIndex, g, i); }); });
      trigrams(m.name).forEach(function (g) { push(triIndex, g, i); });
    });
  }

